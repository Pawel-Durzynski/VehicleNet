namespace VehicleNet.Common.Models.Units;

/// <summary>Identifies a unit used by a vehicle specification value.</summary>
public enum MeasurementUnit
{
    /// <summary>No unit.</summary>
    None = 0,
    /// <summary>Millimeters.</summary>
    Millimeter,
    /// <summary>Meters.</summary>
    Meter,
    /// <summary>Kilometers.</summary>
    Kilometer,
    /// <summary>Cubic centimeters.</summary>
    CubicCentimeter,
    /// <summary>Liters.</summary>
    Liter,
    /// <summary>Degrees.</summary>
    Degree,
    /// <summary>Horsepower.</summary>
    Horsepower,
    /// <summary>Kilowatts.</summary>
    Kilowatt,
    /// <summary>Newton-meters.</summary>
    NewtonMeter,
    /// <summary>Revolutions per minute.</summary>
    Rpm,
    /// <summary>A discrete count.</summary>
    Count,
    /// <summary>Years.</summary>
    Year,
    /// <summary>A unitless ratio.</summary>
    Ratio,
    /// <summary>Kilograms.</summary>
    Kilogram,
    /// <summary>Seconds.</summary>
    Second,
    /// <summary>Kilometers per hour.</summary>
    KilometerPerHour,
    /// <summary>Liters per 100 kilometers.</summary>
    LiterPer100Kilometer,
    /// <summary>Grams per kilometer.</summary>
    GramPerKilometer,
    /// <summary>Kilowatt-hours.</summary>
    KilowattHour
}
